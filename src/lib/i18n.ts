import { ref } from 'vue'

export type Lang = 'nl' | 'en'
function initial(): Lang {
  try {
    return (localStorage.getItem('rn-lang') as Lang) || 'nl'
  } catch {
    return 'nl'
  }
}
export const lang = ref<Lang>(initial())
export function toggleLang() {
  lang.value = lang.value === 'nl' ? 'en' : 'nl'
  try {
    localStorage.setItem('rn-lang', lang.value)
  } catch {
    /* */
  }
  document.documentElement.lang = lang.value
}

